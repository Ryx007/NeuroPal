import Foundation

/// The constant tables of packages/tokens/src/tokens.js, typed and IN THEIR
/// JS ORDER. Order matters: the JS picks "the first preset that matches",
/// "the earliest tile", and the studio lists options in object-key order —
/// so the tables are read from tokens-data.json with an order-keeping
/// parser (`JSONValue` objects are Swift dictionaries and lose it).
public struct TokenTables: Sendable {
    public struct NamedValue: Hashable, Sendable {
        public let name: String
        public let value: String
    }

    public struct SignalBase: Hashable, Sendable {
        public let name: String
        public let dark: Bool
        /// The colour fields (surface…warn, line, control, shadow, grid, palBody).
        public let colors: [String: String]
        public let panelAlpha: Double
        public let gridAlpha: Double

        public func color(_ key: String) -> String { colors[key] ?? "#FF00FF" }
    }

    public struct NamedSignal: Hashable, Sendable {
        public let name: String
        public let signal: Appearance.Signal
    }

    public struct SignalLook: Hashable, Sendable {
        public let name: String
        public let signal: Appearance.Signal
        public let desc: String
    }

    public struct ClassicLook: Hashable, Sendable {
        public let name: String
        public let theme: String
        public let accent: String
        public let desc: String
    }

    public struct TypeRole: Hashable, Sendable {
        public let family: String
        public let weight: Int
        /// Width axis in percent (Signal's display face), nil = normal.
        public let width: Int?
    }

    public struct PalVoice: Hashable, Sendable {
        public let name: String
        /// AVSpeech-style multipliers from PAL_OPTIONS.voice ([rate, pitch]).
        public let rate: Double
        public let pitch: Double
    }

    public struct HomeTileInfo: Hashable, Sendable {
        public let id: String
        public let name: String
        public let short: String
        public let words: [String]
    }

    public let tokensVersion: Int
    public let appearanceVersion: Int

    // Classic
    public let classicThemes: [String: [String: String]]
    public let classicAccentVariants: [String: [String: [String: String]]]
    public let classicThemeNames: [String]
    public let classicAccentNames: [String]
    /// radius, radiusControl, radiusMedium, border, shadow, glassAlpha, blur
    public let classicShape: [String: Double]
    public let classicHomeDefault: Appearance.Home

    // Signal
    /// In SIGNAL_BASES order (Graphite, Concrete, Black, Warm).
    public let signalBases: [SignalBase]
    public let signalAccents: [NamedValue]
    public let signalExtraAccentNames: [String: String]
    public let signalOptions: [String: [String]]
    public let signalBrutalityLevels: [Int]
    public let signalCorners: [String: Double]
    public let signalBrutalityBorder: [Double]
    public let signalBrutalityShadow: [Double]
    public let signalMotionSpeed: [String: Double]
    /// The red ("Overwhelmed") state calms every field: speed × and amplitude ×.
    public let redStateFieldSpeed: Double
    public let redStateFieldAmplitude: Double
    public let signalDefault: Appearance.Signal
    public let signalPresets: [NamedSignal]

    // Looks
    public let signalLooks: [SignalLook]
    public let classicLooks: [ClassicLook]

    /// skin ("classic" | "signal") → role → face.
    public let typeRoles: [String: [String: TypeRole]]

    // Pal
    /// name → CSS border-radius shape (the web's drawing); order = PAL_OPTIONS.shape.
    public let palShapes: [NamedValue]
    /// name → body hex.
    public let palColours: [NamedValue]
    public let palEyes: [String]
    public let palMouths: [String]
    public let palExtras: [String]
    /// talk style → sample template with {task}.
    public let palTalk: [NamedValue]
    public let palVoices: [PalVoice]
    public let palDefault: Appearance.Pal
    /// style → key → line; styles in PAL_LINES order.
    public let palLines: [String: [String: String]]
    public let palLineStyles: [String]

    // Home
    public let homeTiles: [HomeTileInfo]
    public let homeDefault: Appearance.Home
    public let homeSizes: [String]
    public let homeRuleScopes: [String]
    public let homeRuleActs: [String]

    public func signalBase(_ name: String) -> SignalBase? { signalBases.first { $0.name == name } }
    public func homeTile(_ id: String) -> HomeTileInfo? { homeTiles.first { $0.id == id } }
    public func palColourHex(_ name: String) -> String? { palColours.first { $0.name == name }?.value }
    public func options(_ key: String) -> [String] { signalOptions[key] ?? [] }
}

extension TokenTables {
    /// Parses tokens-data.json (GENERATED by packages/tokens/scripts/sync.js).
    init(data: Data) throws {
        let root = try OrderedJSON.parse(data)
        func need(_ key: String) throws -> OrderedJSON {
            guard let v = root[key] else { throw OrderedJSON.Failure("tokens-data.json: \(key) is missing") }
            return v
        }
        func strings(_ v: OrderedJSON?) -> [String] { v?.array?.compactMap(\.string) ?? [] }
        func stringMap(_ v: OrderedJSON?) -> [String: String] {
            Dictionary((v?.pairs ?? []).compactMap { k, x in x.string.map { (k, $0) } }, uniquingKeysWith: { a, _ in a })
        }
        func numberMap(_ v: OrderedJSON?) -> [String: Double] {
            Dictionary((v?.pairs ?? []).compactMap { k, x in x.number.map { (k, $0) } }, uniquingKeysWith: { a, _ in a })
        }
        func signal(_ v: OrderedJSON?) -> Appearance.Signal {
            Appearance.Signal(
                acc: v?["acc"]?.string ?? "#FF3D2E", base: v?["base"]?.string ?? "Graphite",
                motion: v?["motion"]?.string ?? "Lively", field: v?["field"]?.string ?? "Chladni",
                brutality: Int(v?["brutality"]?.number ?? 2), corners: v?["corners"]?.string ?? "Soft",
                texture: v?["texture"]?.string ?? "Grain", type: v?["type"]?.string ?? "Wide")
        }
        func home(_ v: OrderedJSON?) -> Appearance.Home {
            let tiles = (v?["tiles"]?.array ?? []).map { t in
                Appearance.HomeTile(id: t["id"]?.string ?? "", size: t["size"]?.string ?? "M", hidden: t["hidden"]?.bool ?? false)
            }
            let rules = (v?["rules"]?.array ?? []).map { r in
                Appearance.HomeRule(scope: r["scope"]?.string ?? "", tile: r["tile"]?.string ?? "", act: r["act"]?.string ?? "")
            }
            return Appearance.Home(tiles: tiles, rules: rules)
        }

        tokensVersion = Int(try need("tokensVersion").number ?? 0)
        appearanceVersion = Int(try need("appearanceVersion").number ?? 1)

        let themes = try need("classicThemes")
        classicThemes = Dictionary(uniqueKeysWithValues: (themes.pairs ?? []).map { ($0.0, stringMap($0.1)) })
        let variants = try need("classicAccentVariants")
        classicAccentVariants = Dictionary(uniqueKeysWithValues: (variants.pairs ?? []).map { theme, accents in
            (theme, Dictionary(uniqueKeysWithValues: (accents.pairs ?? []).map { ($0.0, stringMap($0.1)) }))
        })
        classicThemeNames = strings(try need("classicThemeNames"))
        classicAccentNames = strings(try need("classicAccentNames"))
        classicShape = numberMap(try need("classicShape"))
        classicHomeDefault = home(try need("classicHomeDefault"))

        signalBases = (try need("signalBases").pairs ?? []).map { name, b in
            var colors: [String: String] = [:]
            for (k, x) in b.pairs ?? [] { if let s = x.string { colors[k] = s } }
            return SignalBase(name: name, dark: b["dark"]?.bool ?? true, colors: colors,
                              panelAlpha: b["panelAlpha"]?.number ?? 0.66, gridAlpha: b["gridAlpha"]?.number ?? 0)
        }
        signalAccents = (try need("signalAccents").array ?? []).map {
            NamedValue(name: $0["name"]?.string ?? "", value: $0["hex"]?.string ?? "")
        }
        signalExtraAccentNames = stringMap(try need("signalExtraAccentNames"))
        let options = try need("signalOptions")
        var opts: [String: [String]] = [:]
        for (k, v) in options.pairs ?? [] where k != "brutality" { opts[k] = strings(v) }
        signalOptions = opts
        signalBrutalityLevels = (options["brutality"]?.array ?? []).compactMap { $0.number.map { Int($0) } }
        signalCorners = numberMap(try need("signalCorners"))
        let brutality = try need("signalBrutality")
        signalBrutalityBorder = (brutality["border"]?.array ?? []).compactMap(\.number)
        signalBrutalityShadow = (brutality["shadow"]?.array ?? []).compactMap(\.number)
        signalMotionSpeed = numberMap(try need("signalMotionSpeed"))
        let red = try need("redStateField")
        redStateFieldSpeed = red["speed"]?.number ?? 0.3
        redStateFieldAmplitude = red["amplitude"]?.number ?? 0.45
        signalDefault = signal(try need("signalDefault"))
        signalPresets = (try need("signalPresets").pairs ?? []).map { NamedSignal(name: $0.0, signal: signal($0.1)) }

        let looks = try need("looks")
        signalLooks = (looks["signal"]?.pairs ?? []).map { name, d in
            SignalLook(name: name, signal: signal(d["sig"]), desc: d["desc"]?.string ?? "")
        }
        classicLooks = (looks["classic"]?.pairs ?? []).map { name, d in
            ClassicLook(name: name, theme: d["theme"]?.string ?? "dark", accent: d["accent"]?.string ?? "ruby",
                        desc: d["desc"]?.string ?? "")
        }

        typeRoles = Dictionary(uniqueKeysWithValues: (try need("typeRoles").pairs ?? []).map { skin, roles in
            (skin, Dictionary(uniqueKeysWithValues: (roles.pairs ?? []).map { role, r in
                (role, TypeRole(family: r["family"]?.string ?? "", weight: Int(r["weight"]?.number ?? 400),
                                width: r["width"]?.number.map { Int($0) }))
            }))
        })

        let pal = try need("palOptions")
        palShapes = (pal["shape"]?.pairs ?? []).map { NamedValue(name: $0.0, value: $0.1.string ?? "") }
        palColours = (pal["colour"]?.pairs ?? []).map { NamedValue(name: $0.0, value: $0.1.string ?? "") }
        palEyes = strings(pal["eyes"])
        palMouths = strings(pal["mouth"])
        palExtras = strings(pal["extra"])
        palTalk = (pal["talk"]?.pairs ?? []).map { NamedValue(name: $0.0, value: $0.1.string ?? "") }
        palVoices = (pal["voice"]?.pairs ?? []).map { name, v in
            PalVoice(name: name, rate: v[0]?.number ?? 1, pitch: v[1]?.number ?? 1)
        }
        let pd = try need("palDefault")
        palDefault = Appearance.Pal(
            name: pd["name"]?.string ?? "Pal", shape: pd["shape"]?.string ?? "Pebble", colour: pd["colour"]?.string ?? "Chalk",
            eyes: pd["eyes"]?.string ?? "Visor", mouth: pd["mouth"]?.string ?? "Smile", extra: pd["extra"]?.string ?? "Headphones",
            talk: pd["talk"]?.string ?? "Gentle", voice: pd["voice"]?.string ?? "Soft", people: pd["people"]?.bool ?? true)
        let lines = try need("palLines")
        palLineStyles = (lines.pairs ?? []).map(\.0)
        palLines = Dictionary(uniqueKeysWithValues: (lines.pairs ?? []).map { ($0.0, stringMap($0.1)) })

        homeTiles = (try need("homeTiles").pairs ?? []).map { id, t in
            HomeTileInfo(id: id, name: t["name"]?.string ?? id, short: t["short"]?.string ?? id.uppercased(),
                         words: strings(t["words"]))
        }
        homeDefault = home(try need("homeDefault"))
        homeSizes = strings(try need("homeSizes"))
        homeRuleScopes = strings(try need("homeRuleScopes"))
        homeRuleActs = strings(try need("homeRuleActs"))
    }
}

/// A JSON value whose objects keep their key order. Only for reading the
/// generated token tables.
enum OrderedJSON {
    case null
    case bool(Bool)
    case number(Double)
    case string(String)
    case array([OrderedJSON])
    case object([(String, OrderedJSON)])

    struct Failure: Error, CustomStringConvertible {
        let description: String
        init(_ description: String) { self.description = description }
    }

    subscript(key: String) -> OrderedJSON? {
        if case .object(let pairs) = self { return pairs.first { $0.0 == key }?.1 }
        return nil
    }

    subscript(index: Int) -> OrderedJSON? {
        if case .array(let a) = self, a.indices.contains(index) { return a[index] }
        return nil
    }

    var pairs: [(String, OrderedJSON)]? { if case .object(let p) = self { return p }; return nil }
    var array: [OrderedJSON]? { if case .array(let a) = self { return a }; return nil }
    var string: String? { if case .string(let s) = self { return s }; return nil }
    var number: Double? { if case .number(let n) = self { return n }; return nil }
    var bool: Bool? { if case .bool(let b) = self { return b }; return nil }

    static func parse(_ data: Data) throws -> OrderedJSON {
        var p = Parser(bytes: Array(data))
        p.skipSpace()
        let v = try p.value()
        p.skipSpace()
        guard p.i == p.bytes.count else { throw Failure("trailing characters at \(p.i)") }
        return v
    }

    private struct Parser {
        let bytes: [UInt8]
        var i = 0

        init(bytes: [UInt8]) {
            // Skip a UTF-8 byte-order mark.
            self.bytes = bytes.starts(with: [0xEF, 0xBB, 0xBF]) ? Array(bytes.dropFirst(3)) : bytes
        }

        mutating func skipSpace() {
            while i < bytes.count, [0x20, 0x09, 0x0A, 0x0D].contains(bytes[i]) { i += 1 }
        }

        mutating func expect(_ literal: String) throws {
            let l = Array(literal.utf8)
            guard i + l.count <= bytes.count, Array(bytes[i..<i + l.count]) == l else { throw Failure("expected \(literal) at \(i)") }
            i += l.count
        }

        mutating func value() throws -> OrderedJSON {
            guard i < bytes.count else { throw Failure("unexpected end") }
            switch bytes[i] {
            case UInt8(ascii: "{"): return try object()
            case UInt8(ascii: "["): return try array()
            case UInt8(ascii: "\""): return .string(try string())
            case UInt8(ascii: "t"): try expect("true"); return .bool(true)
            case UInt8(ascii: "f"): try expect("false"); return .bool(false)
            case UInt8(ascii: "n"): try expect("null"); return .null
            default: return .number(try number())
            }
        }

        mutating func object() throws -> OrderedJSON {
            i += 1
            var pairs: [(String, OrderedJSON)] = []
            skipSpace()
            if i < bytes.count, bytes[i] == UInt8(ascii: "}") { i += 1; return .object(pairs) }
            while true {
                skipSpace()
                let key = try string()
                skipSpace()
                try expect(":")
                skipSpace()
                pairs.append((key, try value()))
                skipSpace()
                guard i < bytes.count else { throw Failure("unterminated object") }
                if bytes[i] == UInt8(ascii: ",") { i += 1; continue }
                if bytes[i] == UInt8(ascii: "}") { i += 1; return .object(pairs) }
                throw Failure("expected , or } at \(i)")
            }
        }

        mutating func array() throws -> OrderedJSON {
            i += 1
            var items: [OrderedJSON] = []
            skipSpace()
            if i < bytes.count, bytes[i] == UInt8(ascii: "]") { i += 1; return .array(items) }
            while true {
                skipSpace()
                items.append(try value())
                skipSpace()
                guard i < bytes.count else { throw Failure("unterminated array") }
                if bytes[i] == UInt8(ascii: ",") { i += 1; continue }
                if bytes[i] == UInt8(ascii: "]") { i += 1; return .array(items) }
                throw Failure("expected , or ] at \(i)")
            }
        }

        mutating func string() throws -> String {
            guard i < bytes.count, bytes[i] == UInt8(ascii: "\"") else { throw Failure("expected a string at \(i)") }
            i += 1
            var units: [UInt16] = []
            var raw: [UInt8] = []
            func flushRaw() {
                units.append(contentsOf: String(decoding: raw, as: UTF8.self).utf16)
                raw.removeAll()
            }
            while i < bytes.count {
                let c = bytes[i]
                if c == UInt8(ascii: "\"") {
                    i += 1
                    flushRaw()
                    return String(decoding: units, as: UTF16.self)
                }
                if c == UInt8(ascii: "\\") {
                    flushRaw()
                    guard i + 1 < bytes.count else { break }
                    let e = bytes[i + 1]
                    i += 2
                    switch e {
                    case UInt8(ascii: "\""): units.append(0x22)
                    case UInt8(ascii: "\\"): units.append(0x5C)
                    case UInt8(ascii: "/"): units.append(0x2F)
                    case UInt8(ascii: "b"): units.append(0x08)
                    case UInt8(ascii: "f"): units.append(0x0C)
                    case UInt8(ascii: "n"): units.append(0x0A)
                    case UInt8(ascii: "r"): units.append(0x0D)
                    case UInt8(ascii: "t"): units.append(0x09)
                    case UInt8(ascii: "u"):
                        guard i + 4 <= bytes.count, let u = UInt16(String(decoding: bytes[i..<i + 4], as: UTF8.self), radix: 16)
                        else { throw Failure("bad \\u escape at \(i)") }
                        units.append(u)
                        i += 4
                    default: throw Failure("bad escape at \(i)")
                    }
                    continue
                }
                raw.append(c)
                i += 1
            }
            throw Failure("unterminated string")
        }

        mutating func number() throws -> Double {
            let start = i
            while i < bytes.count, "+-0123456789.eE".utf8.contains(bytes[i]) { i += 1 }
            guard i > start, let v = Double(String(decoding: bytes[start..<i], as: UTF8.self)) else {
                throw Failure("bad number at \(start)")
            }
            return v
        }
    }
}
