import Foundation

/// The palette and appearance logic — a port of packages/tokens/src, proven
/// against packages/tokens/fixtures/cases.json (Tests/NPTokensTests). The
/// JS stays the source of truth: change it there, run
/// `node packages/tokens/scripts/sync.js`, then mirror the change here.
///
/// Files: JSCompat (JS number/string rules), ColorMath (color.js),
/// TokenTables (tokens.js, read in order from tokens-data.json),
/// Classic, Signal, AppearanceLogic (appearance.js), Home, Pal, Interpret.
public enum Tokens {
    /// TOKENS_VERSION of packages/tokens this port follows.
    public static let version = 2

    /// The raw constant tables, decoded from tokens-data.json — GENERATED by
    /// packages/tokens/scripts/sync.js. (Unordered; prefer `tables`.)
    public static let data: JSONValue = {
        guard let bytes = dataFile, let value = try? JSONDecoder().decode(JSONValue.self, from: bytes)
        else { return .object([:]) }
        return value
    }()

    /// The same tables, typed and in their JS order.
    public static let tables: TokenTables = {
        guard let bytes = dataFile else { preconditionFailure("NPTokens: tokens-data.json is missing from the bundle") }
        do {
            return try TokenTables(data: bytes)
        } catch {
            preconditionFailure("NPTokens: tokens-data.json is unreadable (\(error))")
        }
    }()

    private static let dataFile: Data? = {
        guard let url = Bundle.module.url(forResource: "tokens-data", withExtension: "json") else { return nil }
        return try? Data(contentsOf: url)
    }()

    /// APPEARANCE_VERSION (the `v` of the appearance object).
    public static var appearanceVersion: Int { tables.appearanceVersion }

    /// resolveAppearancePalette: the palette for whichever skin is on.
    public static func palette(for appearance: Appearance) -> Palette {
        appearance.skin == .signal
            ? resolveSignalPalette(appearance.signal)
            : resolveClassicPalette(theme: appearance.classic.theme, accent: appearance.classic.accent)
    }

    /// effectiveMotion(level, reduceMotion): the OS Reduce Motion setting
    /// always wins — "Still" means no animation anywhere.
    public static func effectiveMotion(_ level: String, reduceMotion: Bool) -> String {
        reduceMotion ? "Still" : level
    }
}
