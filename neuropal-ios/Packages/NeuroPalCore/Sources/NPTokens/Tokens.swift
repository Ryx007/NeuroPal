import Foundation

/// The palette and appearance logic — a port of packages/tokens/src.
///
/// SKELETON: the resolvers below return the defaults until the port lands.
/// The port must reproduce packages/tokens/fixtures/cases.json exactly
/// (Tests/NPTokensTests); the Dart port in neuropal-flutter/lib/theme is a
/// second reference that already passes the same fixtures.
public enum Tokens {
    /// TOKENS_VERSION of packages/tokens this port follows.
    public static let version = 2

    /// The constant tables (themes, accents, bases, looks, type roles, Pal
    /// options, Home tiles), decoded from tokens-data.json — GENERATED by
    /// packages/tokens/scripts/sync.js.
    public static let data: JSONValue = {
        guard let url = Bundle.module.url(forResource: "tokens-data", withExtension: "json"),
              let bytes = try? Data(contentsOf: url),
              let value = try? JSONDecoder().decode(JSONValue.self, from: bytes)
        else { return .object([:]) }
        return value
    }()

    /// normalizeAppearance: any JSON (or nil) → a complete, valid appearance.
    public static func normalizeAppearance(_ json: JSONValue?) -> Appearance {
        guard let json, let decoded = try? json.decode(Appearance.self) else { return .default }
        return decoded // SKELETON: no per-field normalisation yet
    }

    /// resolveAppearancePalette
    public static func palette(for appearance: Appearance) -> Palette {
        appearance.skin == .signal
            ? resolveSignalPalette(appearance.signal)
            : resolveClassicPalette(theme: appearance.classic.theme, accent: appearance.classic.accent)
    }

    /// resolveClassicPalette({theme, accent})
    public static func resolveClassicPalette(theme: String, accent: String) -> Palette {
        .classicDefault // SKELETON
    }

    /// resolveSignalPalette(signal) — `signal` already normalised.
    public static func resolveSignalPalette(_ signal: Appearance.Signal) -> Palette {
        .signalDefault // SKELETON
    }

    /// effectiveTiles(home, date): the tiles Home shows today, in order —
    /// base order and hidden flags, then the Weekdays/Weekends rules.
    public static func effectiveTiles(_ home: Appearance.Home, date: Date = Date()) -> [Appearance.HomeTile] {
        home.tiles.filter { !$0.hidden } // SKELETON: rules not applied yet
    }

    /// effectiveMotion(level, reduceMotion): the OS Reduce Motion setting
    /// always wins — "Still" means no animation anywhere.
    public static func effectiveMotion(_ level: String, reduceMotion: Bool) -> String {
        reduceMotion ? "Still" : level
    }
}
