// NeuroPal's platform-neutral code. It builds for macOS too, so the tests
// run on a Mac without a simulator:
//   swift test --package-path Packages/NeuroPalCore
import PackageDescription

let package = Package(
    name: "NeuroPalCore",
    platforms: [.iOS(.v18), .macOS(.v15)],
    products: [
        .library(name: "NPTokens", targets: ["NPTokens"]),
        .library(name: "NPCore", targets: ["NPCore"]),
        .library(name: "NPDay", targets: ["NPDay"]),
    ],
    targets: [
        // The palette and appearance logic, ported from packages/tokens and
        // proven against its fixtures. tokens-data.json is GENERATED by
        // packages/tokens/scripts/sync.js — never edit it here.
        .target(name: "NPTokens", resources: [.process("Resources")]),
        // Server models, the API (HTTP + mock), the signed-in session.
        .target(name: "NPCore", dependencies: ["NPTokens"], resources: [.copy("Mock/MockBook")]),
        // Today: check-ins, anchors, the minimum day, Pal's offline logic.
        // Stored in the App Group so the widgets read the same data.
        .target(name: "NPDay", dependencies: ["NPCore"]),
        .testTarget(name: "NPTokensTests", dependencies: ["NPTokens"], resources: [.copy("Fixtures")]),
        // Fixtures/reader-words.json is GENERATED from the web and Expo
        // readers by scripts/make-reader-words.sh — never edit it here.
        .testTarget(name: "NPCoreTests", dependencies: ["NPCore"], resources: [.copy("Fixtures")]),
        .testTarget(name: "NPDayTests", dependencies: ["NPDay"]),
    ],
    swiftLanguageModes: [.v5]
